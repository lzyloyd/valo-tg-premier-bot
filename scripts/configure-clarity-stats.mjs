import fs from 'node:fs/promises';
import path from 'node:path';
import {config} from '../src/config.js';
import {statsTeams,withStatsTeam} from '../src/statsTeams.js';
import {displayName,trackerProfileUrl} from '../src/statsRoster.js';
import {getSpreadsheetMeta,getValues,getSpreadsheetDetails,batchUpdate} from '../src/sheetsClient.js';
import {resetHeatmapPlaceholders,ANCHOR_FIRST_ROW,BLOCK_SIZE,ROSTER_SIZE,TABLE1_FIRST_ROW,TABLE2_FIRST_ROW} from '../src/sheetsStats.js';

const team=statsTeams.find(t=>t.id==='clarity');
const apply=process.argv.includes('--apply');
if(team.spreadsheetId === config.statsSpreadsheetId)throw Error('Clarity must use a separate spreadsheet.');
await withStatsTeam(team,async()=>{
 const metadata=await getSpreadsheetMeta(team.spreadsheetId);
 const sheet=metadata.find(s=>s.sheetId===1469136185);
 if(!sheet || !['Статистика за V26A5',team.overallTab].includes(sheet.title))throw Error('Unexpected Clarity template tab.');
 if(metadata.some(s=>s.sheetId!==sheet.sheetId))throw Error('The workbook already contains extra tabs; inspect before rewriting the template.');
 const quote=title=>"'"+title.replaceAll("'","''")+"'";
 const lastCol=String.fromCharCode(64+Math.floor((sheet.gridProperties.columnCount-1)/26))+String.fromCharCode(65+(sheet.gridProperties.columnCount-1)%26);
 const endCol=sheet.gridProperties.columnCount<=26?String.fromCharCode(64+sheet.gridProperties.columnCount):lastCol;
 const lastRow=ANCHOR_FIRST_ROW+BLOCK_SIZE*ROSTER_SIZE-1;
 const values=await getValues(team.spreadsheetId,`${quote(sheet.title)}!R1:${endCol}${lastRow}`);
 if(values.flat().some(value=>value!==''))throw Error('Game data already exists; refusing to relabel player blocks.');
 const snapshot=await getSpreadsheetDetails(team.spreadsheetId,[`${quote(sheet.title)}!A1:${endCol}${lastRow}`]);
 const hasValidation=snapshot.sheets.some(s=>s.data?.some(grid=>grid.rowData?.some(row=>row.values?.some(cell=>cell.dataValidation))));
 if(hasValidation)throw Error('Template contains validation; inspect constraints before editing.');
 const summary={spreadsheet:team.spreadsheetId,sheetId:sheet.sheetId,oldTitle:sheet.title,newTitle:team.overallTab,players:team.roster.map(r=>r.riotId),emptyPlayerSlots:ROSTER_SIZE-team.roster.length,hasGames:false,apply};
 console.log(JSON.stringify(summary));
 if(!apply)return;
 const backupDir=path.join(config.dataDir,'stats-backups');await fs.mkdir(backupDir,{recursive:true});
 const backup=path.join(backupDir,`clarity-${Date.now()}.json`);await fs.writeFile(backup,JSON.stringify(snapshot));
 const linkedCell=riotId=>({userEnteredValue:{stringValue:displayName(riotId)},textFormatRuns:[{startIndex:0,format:{link:{uri:trackerProfileUrl(riotId)},underline:true}}]});
 const requests=[{updateSheetProperties:{properties:{sheetId:sheet.sheetId,title:team.overallTab,gridProperties:{columnCount:Math.max(78,sheet.gridProperties.columnCount)}},fields:'title,gridProperties.columnCount'}}];
 for(let i=0;i<ROSTER_SIZE;i++) for(const [row,col] of [[TABLE1_FIRST_ROW+i,1],[TABLE2_FIRST_ROW+i,1],[ANCHOR_FIRST_ROW+i*BLOCK_SIZE,16]])requests.push({updateCells:{start:{sheetId:sheet.sheetId,rowIndex:row-1,columnIndex:col},rows:[{values:[team.roster[i]?linkedCell(team.roster[i].riotId):{}]}],fields:'userEnteredValue,textFormatRuns'}});
 requests.push({repeatCell:{range:{sheetId:sheet.sheetId,startRowIndex:0,endRowIndex:lastRow,startColumnIndex:17,endColumnIndex:78},cell:{note:''},fields:'note'}});
 await batchUpdate(team.spreadsheetId,requests);
 await resetHeatmapPlaceholders(team.spreadsheetId,team.overallTab,'Premier',sheet.sheetId);
 const names=await getValues(team.spreadsheetId,`${quote(team.overallTab)}!B3:B10`);
 const errors=(await getValues(team.spreadsheetId,`${quote(team.overallTab)}!B1:P22`)).flat().filter(value=>String(value).startsWith('#'));
 if(errors.length || team.roster.some((r,i)=>names[i]?.[0]!==displayName(r.riotId)))throw Error('Clarity template readback failed.');
 console.log(JSON.stringify({verified:true,backup,players:names.map(row=>row[0]||'')}));
});
